"""Extract advance widths from locally installed fonts; never copy font files."""
import json
import os
import argparse
from pathlib import Path
from fontTools.ttLib import TTFont

FONT_FILES = {
    'proxima-nova-semibold': ('Proxima Nova SemiBold', 'Mark Simonson - Proxima Nova Semibold.ttf'),
    'montserrat-semibold': ('Montserrat SemiBold', 'Montserrat-SemiBold.ttf'),
    'inter-semibold': ('Inter SemiBold (28pt)', 'Inter_28pt-SemiBold.ttf'),
    'roboto-semibold': ('Roboto SemiBold', 'Roboto-SemiBold.ttf'),
    'open-sans-semibold': ('Open Sans SemiBold', 'OpenSans-SemiBold.ttf'),
}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-dir', type=Path, default=Path(os.environ['LOCALAPPDATA']) / 'Microsoft/Windows/Fonts')
    directory = parser.parse_args().font_dir
    characters = ''.join(chr(code) for code in range(32, 127))
    characters += ''.join(chr(code) for code in range(160, 384)) + '‘’“”–—…€'
    profiles = {}
    for identifier, (label, filename) in FONT_FILES.items():
        with TTFont(directory / filename) as font:
            cmap = font.getBestCmap()
            units = font['head'].unitsPerEm
            profiles[identifier] = {
                'label': label, 'weight': font['OS/2'].usWeightClass,
                'advances': {char: round(font['hmtx'][cmap[ord(char)]][0] / units, 6)
                             for char in characters if ord(char) in cmap},
            }
    output = Path(__file__).resolve().parents[1] / 'src/captions/font-metrics.js'
    output.write_text(
        '// Generated by scripts/extract-caption-font-metrics.py from installed font advance tables.\n'
        '// Numeric measurements only; no font binaries are included. Widths are in em.\n'
        'export const FONT_METRICS = ' + json.dumps(profiles, ensure_ascii=True, indent=2) + ';\n',
        encoding='utf-8')
    for identifier, profile in profiles.items():
        print(identifier, 'weight', profile['weight'], 'glyphs', len(profile['advances']))

if __name__ == '__main__':
    main()
